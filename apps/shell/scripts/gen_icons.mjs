// Rebuilds src/widgets/icons.gen.ts from scripts/icons.json.
//
// The shell draws Lucide icons as inline SVG: thin, round-ended strokes, the
// nearest open-licensed match for the Mac's SF Symbols (which only Apple's
// platforms may use). icons.json maps each name the code uses to a Lucide
// icon; this fetches those icons at the pinned version and keeps only what is
// inside each <svg>, since Symbol.tsx draws the element itself.
//
//     pnpm gen:icons
//
// Pinned because Lucide renames icons between versions, and a name that
// vanished would otherwise be found as an empty box in a screenshot. Any name
// the pinned version does not have fails the run.

import { readFileSync, writeFileSync } from "node:fs";

const list = JSON.parse(
  readFileSync(new URL("./icons.json", import.meta.url), "utf8"),
);
const base = `https://raw.githubusercontent.com/lucide-icons/lucide/${list.lucide}/icons`;

const wanted = [...new Set(Object.values(list.icons))].sort();
const bodies = {};
const missing = [];

await Promise.all(
  wanted.map(async (name) => {
    const response = await fetch(`${base}/${name}.svg`);
    if (!response.ok) {
      missing.push(name);
      return;
    }
    const svg = await response.text();
    const inner = /<svg[^>]*>([\s\S]*)<\/svg>/.exec(svg)?.[1];
    if (!inner) {
      missing.push(name);
      return;
    }
    bodies[name] = inner.replace(/\s*\n\s*/g, "").trim();
  }),
);

if (missing.length) {
  console.error(
    `Lucide ${list.lucide} has no icon called: ${missing.sort().join(", ")}`,
  );
  process.exit(1);
}

const lines = Object.entries(list.icons)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(
    ([name, lucide]) =>
      `  ${JSON.stringify(name)}: ${JSON.stringify(bodies[lucide])},`,
  );

writeFileSync(
  new URL("../src/widgets/icons.gen.ts", import.meta.url),
  `// Generated by scripts/gen_icons.mjs from scripts/icons.json — do not edit.
// Lucide ${list.lucide} (ISC), the inside of each icon's 24×24 <svg>.

export const ICONS: Record<string, string> = {
${lines.join("\n")}
};
`,
);
console.log(`${lines.length} icons from Lucide ${list.lucide}`);
